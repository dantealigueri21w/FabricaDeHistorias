package pe.appmobile.fabricadehistorias.domain.model

/**
 * Los seis tramos del esqueleto de la fábula. El niño no escribe "un cuento":
 * escribe una frase corta en cada tramo, y el cuento sale de la suma.
 *
 * El orden del enum es el orden narrativo correcto.
 */
enum class Tramo {
    ERASE_UNA_VEZ,
    TODOS_LOS_DIAS,
    HASTA_QUE_UN_DIA,
    POR_ESO,
    HASTA_QUE_POR_FIN,
    Y_DESDE_ENTONCES
}
